 * MoonBit 面罩挖空的 mask id。文档内必须唯一,而设备卡会把同一枚图标渲染 N 份,
 * 所以每个实例领一个号 —— 照 FileIcon.vue 的教训:模块级自增计数器在
 * `<script setup>` 下每次 setup() 重跑都会归零,永远拿到同一个号。
