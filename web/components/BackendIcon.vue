import { backendIconKind, backendIconLabel } from '../utils/backend-icon';

const props = defineProps<{
  /** 后端形态(node / rust / moonbit);undefined = 旧版本对端未宣告 —— 此时不渲染。 */
  runtime?: string;
  /** 不在线:整枚图标去色 + 减淡(与 OsIcon 同一口径)。 */
  offline?: boolean;
  /** 覆盖 title / aria-label 的文本。 */
  hint?: string;
  /** 边长(px)。默认 14 适配顶栏 chip,设备卡头像位传 18。 */
  size?: number;
}>();

