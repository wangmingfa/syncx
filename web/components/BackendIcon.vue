 *    但沿用 OsIcon 的 grayscale 惯例:离线对端整体减淡,与同排的系统图标同一语言。
 *
 * Rust 与 MoonBit 的图形直接沿用 FileIcon.vue 里已经在用的那两笔(齿轮 evenodd
 * 镂空 R / 吉祥物 mask 挖面罩),同一种语言在文件图标与设备卡上保持同一张脸。
 */
